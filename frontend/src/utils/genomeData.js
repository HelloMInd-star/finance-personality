// MBTI 匹配分数
export const calculateMBTIMatch = (userMBTI, masterMBTI) => {
  if (userMBTI === masterMBTI) return 100;
  let diff = 0;
  for (let i = 0; i < 4; i++) {
    if (userMBTI[i] !== masterMBTI[i]) diff++;
  }
  const scoreMap = { 1: 65, 2: 40, 3: 20, 4: 5 };
  return scoreMap[diff] || 0;
};
